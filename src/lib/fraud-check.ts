export type FraudSignal = typeof signals[number]["id"];

export function checkFraudMessage(text: string): FraudSignal[] {
  const message = text.normalize("NFKC").replace(/\s+/gu, "");
  return signals.filter(({ pattern }) => pattern.test(message)).map(({ id }) => id);
}

export const fraudSignalAdvice = Object.fromEntries(signals.map(({ id, label, action }) => [id, { label, action }])) as
  Record<FraudSignal, { label: string; action: string }>;
